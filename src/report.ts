// Renders investigation/findings.md. Site-derived strings are escaped and
// fenced: they are data, never instructions.

import type { EndpointRecord, EvidenceRecord, Investigation } from "./core/types.ts";
import { fieldNames } from "./analysis/schema.ts";

const STATUS_LABEL: Record<EndpointRecord["status"], string> = {
  confirmed: "✅ confirmed by test",
  observed: "👀 observed, not tested",
  inferred: "🔎 inferred from evidence",
  unavailable: "⛔ unavailable / not verifiable",
};

export const md = (s: string) => s.replace(/[|`<>\r\n]/g, (c) => ({ "|": "\\|", "`": "'", "<": "&lt;", ">": "&gt;", "\r": " ", "\n": " " })[c] ?? c);

export function renderFindings(inv: Investigation, evidence: EvidenceRecord[]): string {
  const L: string[] = [];
  const by = (s: EndpointRecord["status"]) => inv.endpoints.filter((e) => e.status === s);
  L.push(`# Findings: ${md(inv.input.url)}`, "");
  L.push(`> Generated by rea-from-api ${inv.tool.version} on ${inv.finishedAt}. Site content quoted below is untrusted data.`, "");
  L.push(`**Goal:** ${md(inv.input.goal)}`, "");
  L.push(`**Application type:** ${md(inv.appType)}`, "");
  if (inv.tech.length) L.push(`**Technology hints:** ${inv.tech.map((t) => `${md(t.name)} _(${md(t.basis)})_`).join("; ")}`, "");
  L.push(
    `**Budget:** ${inv.budget.requestsUsed}/${inv.budget.requestLimit} direct requests, ${(inv.budget.elapsedMs / 1000).toFixed(1)} s. Browser traffic is driven by REA and not counted.`,
    "",
  );

  L.push("## Summary", "");
  L.push("| Classification | Count |", "|---|---|");
  for (const s of ["confirmed", "observed", "inferred", "unavailable"] as const) L.push(`| ${STATUS_LABEL[s]} | ${by(s).length} |`);
  L.push("");

  const best = inv.endpoints.filter((e) => e.status === "confirmed" && e.responseFormat === "json").slice(0, 5);
  L.push("## Recommended data sources (by goal relevance)", "");
  if (best.length) {
    for (const e of best)
      L.push(`- \`${e.method} ${md(e.urlTemplate)}\`: relevance ${e.goalRelevance}, ${e.documented ? "documented" : "undocumented"}, auth: ${e.auth}${e.pagination ? `, pagination: ${e.pagination.style}` : ""}`);
  } else if (inv.embedded.some((e) => e.schema)) {
    L.push("- No confirmed JSON endpoint. Embedded page data is available (see below); an HTML/embedded-JSON extractor is the viable strategy.");
  } else {
    L.push("- No confirmed machine-readable source. See limitations; consider an official API, a HAR from your own authorized session, or `--seed` URLs from documentation.");
  }
  L.push("");

  L.push("## Strategies executed", "");
  L.push("| Strategy | Status | Detail | ms |", "|---|---|---|---|");
  for (const r of inv.strategies) L.push(`| ${r.id} | ${r.status} | ${md(r.detail)} | ${r.durationMs} |`);
  L.push("");

  L.push("## Endpoints", "");
  for (const s of ["confirmed", "observed", "inferred", "unavailable"] as const) {
    const list = by(s);
    if (!list.length) continue;
    L.push(`### ${STATUS_LABEL[s]} (${list.length})`, "");
    for (const e of list.slice(0, 60)) L.push(...renderEndpoint(e));
    if (list.length > 60) L.push(`_…${list.length - 60} more in endpoints.json_`, "");
  }

  if (inv.embedded.length) {
    L.push("## Embedded data in HTML", "");
    for (const e of inv.embedded)
      L.push(
        `- **${e.kind}** at \`${md(e.selector)}\` on ${md(e.pageUrl)}${e.types ? `: @type: ${e.types.map(md).join(", ")}` : ""}${e.schema ? `: fields: ${fieldNames(e.schema).slice(0, 12).map(md).join(", ")}` : ", not valid JSON"} (evidence ${e.evidenceId}${e.sampleFile ? `, sample \`${e.sampleFile}\`` : ""})`,
      );
    L.push("");
  }

  L.push("## Limitations", "");
  if (inv.limitations.length) for (const l of inv.limitations) L.push(`- ${md(l)}`);
  L.push(
    "- Undocumented endpoints are internal implementation details: they may change without notice and their reuse may be restricted by the site's terms of use. Check the terms before depending on them.",
    "- Only GET/HEAD requests were replayed. Write operations are never executed automatically.",
    "",
  );

  L.push("## Evidence index", "");
  L.push("| id | strategy | kind | summary |", "|---|---|---|---|");
  for (const e of evidence.slice(0, 200)) L.push(`| ${e.id} | ${e.strategy} | ${e.kind} | ${md(e.summary).slice(0, 160)}${e.reaEvidenceId ? ` (REA ${e.reaEvidenceId.slice(0, 15)}…)` : ""} |`);
  if (evidence.length > 200) L.push(`| … | | | ${evidence.length - 200} more in evidence.json |`);
  L.push("");
  return L.join("\n");
}

function renderEndpoint(e: EndpointRecord): string[] {
  const L = [`#### \`${e.method} ${md(e.urlTemplate)}\``, ""];
  L.push(`- id: \`${e.id}\` · test: ${e.testStatus} · confidence: ${e.confidence} · relevance: ${e.goalRelevance}${e.verifiedAt ? ` · verified ${e.verifiedAt}` : ""}`);
  L.push(`- purpose: ${md(e.purpose)}`);
  L.push(`- discovered by: ${e.discoveredBy.join(", ")} · evidence: ${e.evidenceIds.join(", ")}`);
  if (e.queryParams.length) L.push(`- query: ${e.queryParams.map((p) => `\`${md(p.name)}\`(${p.role}${p.example ? `=${md(p.example).slice(0, 30)}` : ""})`).join(", ")}`);
  if (e.pathParams.length) L.push(`- path params: ${e.pathParams.join(", ")}`);
  L.push(`- auth: ${e.auth}${e.authEvidence ? ` (${md(e.authEvidence)})` : ""} · format: ${e.responseFormat}${e.contentType ? ` (${md(e.contentType)})` : ""}`);
  if (e.requiredHeaders.length) L.push(`- header names used: ${e.requiredHeaders.join(", ")} (values never stored)`);
  if (e.pagination) L.push(`- pagination: ${e.pagination.style} (${md(e.pagination.basis)})${e.pagination.itemsField ? ` · items at \`${e.pagination.itemsField}\`` : ""}`);
  if (e.schema) L.push(`- fields: ${fieldNames(e.schema).slice(0, 15).map(md).join(", ")}${fieldNames(e.schema).length > 15 ? ", …" : ""}`);
  if (e.rateLimit) L.push(`- rate-limit headers: ${Object.entries(e.rateLimit).map(([k, v]) => `${k}=${md(v)}`).join(", ")}`);
  if (e.errorsObserved.length) L.push(`- errors: ${e.errorsObserved.map((x) => x.status).join(", ")}`);
  for (const n of e.notes) L.push(`- note: ${md(n)}`);
  L.push("");
  return L;
}
