// Runtime configuration. Values come from options or environment variables.
// Secrets are only ever read from the environment; never hard-code them.

export interface Config {
  /** Replaces the origin of every source URL (useful for tests, proxies, staging). */
  baseUrl?: string;
  timeoutMs: number;
  maxRetries: number;
  /** Longest Retry-After the client will wait before giving up on a 429. */
  maxRetryAfterMs: number;
  /** Minimum delay between two requests (no rate-limit headers observed; conservative default of 2 req/s). */
  minIntervalMs: number;
  cacheTtlMs: number;
  userAgent: string;
  token?: string;
  logger?: (line: string) => void;
}

export function loadConfig(overrides: Partial<Config> = {}): Config {
  const env = process.env;
  return {
    baseUrl: env.PYPI_JSON_BASE_URL || undefined,
    timeoutMs: num(env.PYPI_JSON_TIMEOUT_MS, 15000),
    maxRetries: num(env.PYPI_JSON_MAX_RETRIES, 2),
    maxRetryAfterMs: num(env.PYPI_JSON_MAX_RETRY_AFTER_MS, 10000),
    minIntervalMs: num(env.PYPI_JSON_MIN_INTERVAL_MS, 500),
    cacheTtlMs: num(env.PYPI_JSON_CACHE_TTL_MS, 60000),
    userAgent: env.PYPI_JSON_USER_AGENT || "pypi-json-integration/0.1 (generated by rea-from-api)",
    token: undefined,
    ...overrides,
  };
}

function num(v: string | undefined, d: number): number {
  const n = Number(v);
  return v !== undefined && v !== "" && Number.isFinite(n) ? n : d;
}
